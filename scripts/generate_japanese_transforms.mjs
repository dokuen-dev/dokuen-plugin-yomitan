// Generates app/src/main/java/.../parser/JapaneseTransforms.kt from the original Yomitan's Japanese
// deinflection rules (ext/js/language/ja/japanese-transforms.js), so the port's rules, their word-class
// conditions, and their names stay exactly the original's.
//
// Usage, from this repository's root:
//   node scripts/generate_japanese_transforms.mjs <path to a Yomitan checkout>
//
// The original builds most rules with helper functions, so this loads the file and reads the resulting
// data instead of parsing the source. Japanese only uses suffix and whole-word rules; anything else is an
// error, as is anything the output format cannot hold.

import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
import {join, resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

const OUTPUT = 'app/src/main/java/io/github/dokuendev/dokuen/plugins/dictionary/yomitan/parser/JapaneseTransforms.kt';

const yomitan = process.argv[2];
if (!yomitan) {
    console.error('Usage: node scripts/generate_japanese_transforms.mjs <path to a Yomitan checkout>');
    process.exit(1);
}
const source = resolve(yomitan, 'ext/js/language/ja/japanese-transforms.js');
const {japaneseTransforms} = await import(pathToFileURL(source).href);
const commit = execFileSync('git', ['-C', yomitan, 'rev-parse', 'HEAD'], {encoding: 'utf8'}).trim();

/** A Kotlin string literal. */
function str(value) {
    return '"' + value
        .replace(/\\/g, '\\\\')
        .replace(/"/g, '\\"')
        .replace(/\$/g, '\\$')
        .replace(/\n/g, '\\n')
        .replace(/\r/g, '\\r')
        .replace(/\t/g, '\\t') + '"';
}

/** The literal text a rule's regular expression matches, which must have no special characters. */
function literal(regExp, prefix, suffix) {
    const body = regExp.source;
    if (!body.startsWith(prefix) || !body.endsWith(suffix)) { throw new Error(`Unexpected pattern ${body}`); }
    const text = body.slice(prefix.length, body.length - suffix.length);
    if (/[\\^$.*+?()[\]{}|]/.test(text)) { throw new Error(`Pattern ${body} is not plain text`); }
    return text;
}

/** Condition names as one space-separated string; no condition name contains a space. */
function conditions(names) {
    for (const name of names) {
        if (name.includes(' ')) { throw new Error(`Condition name "${name}" contains a space`); }
    }
    return str(names.join(' '));
}

const lines = [];
lines.push(`// Generated by scripts/generate_japanese_transforms.mjs from the original Yomitan's`);
lines.push(`// ext/js/language/ja/japanese-transforms.js at commit ${commit}.`);
lines.push(`// Do not edit by hand; run the script again instead.`);
lines.push('');
lines.push('package io.github.dokuendev.dokuen.plugins.dictionary.yomitan.parser');
lines.push('');
lines.push('internal object JapaneseTransforms {');
lines.push('    val conditions: List<TransformCondition> = listOf(');
for (const [id, condition] of Object.entries(japaneseTransforms.conditions)) {
    const sub = condition.subConditions ?? [];
    lines.push(`        TransformCondition(${str(id)}, ${condition.isDictionaryForm}, ${conditions(sub)}),`);
}
lines.push('    )');
lines.push('');
lines.push('    val transforms: List<Transform> = listOf(');
for (const [id, transform] of Object.entries(japaneseTransforms.transforms)) {
    const japanese = (transform.i18n ?? []).find((entry) => entry.language === 'ja');
    lines.push('        Transform(');
    lines.push(`            id = ${str(id)},`);
    lines.push(`            name = ${str(transform.name)},`);
    lines.push(`            japaneseName = ${japanese ? str(japanese.name) : 'null'},`);
    lines.push(`            description = ${typeof transform.description === 'string' ? str(transform.description) : 'null'},`);
    lines.push('            rules = listOf(');
    for (const rule of transform.rules) {
        const conditionsIn = conditions(rule.conditionsIn);
        const conditionsOut = conditions(rule.conditionsOut);
        if (rule.type === 'suffix') {
            const inflected = literal(rule.isInflected, '', '$');
            if (inflected.length === 0) { throw new Error(`Empty suffix in transform ${id}`); }
            lines.push(`                suffix(${str(inflected)}, ${str(rule.deinflected)}, ${conditionsIn}, ${conditionsOut}),`);
        } else if (rule.type === 'wholeWord') {
            const inflected = literal(rule.isInflected, '^', '$');
            lines.push(`                wholeWord(${str(inflected)}, ${str(rule.deinflect(''))}, ${conditionsIn}, ${conditionsOut}),`);
        } else {
            throw new Error(`Unsupported rule type ${rule.type} in transform ${id}`);
        }
    }
    lines.push('            )');
    lines.push('        ),');
}
lines.push('    )');
lines.push('}');
lines.push('');

writeFileSync(join(process.cwd(), OUTPUT), lines.join('\n'), 'utf8');
console.log(`Wrote ${OUTPUT} from ${source} at ${commit}`);
